import test from 'node:test';
import assert from 'node:assert/strict';
import { parseLockfile, parseAny, classifySource, toBaseline } from '../src/index.js';

test('npm lockfile v3', () => {
  const m = parseLockfile(JSON.stringify({ lockfileVersion: 3, packages: {
    '': { name: 'x' },
    'node_modules/a': { version: '1.0.0', resolved: 'https://registry.npmjs.org/a/-/a-1.0.0.tgz', integrity: 'sha512-a', hasInstallScript: true },
    'node_modules/a/node_modules/@s/b': { version: '2.0.0', dev: true },
    'node_modules/c': { version: '1.0.0', resolved: 'git+ssh://git@github.com/u/c.git#abc' },
    'packages/ws': { version: '1.0.0' },
    'node_modules/ws-link': { resolved: 'packages/ws', link: true },
  } }), 'npm');
  assert.deepEqual([...m.keys()].sort(), ['@s/b@2.0.0', 'a@1.0.0', 'c@1.0.0']);
  assert.equal(m.get('a@1.0.0').hasInstallScript, true);
  assert.equal(m.get('@s/b@2.0.0').dev, true);
  assert.equal(m.get('c@1.0.0').source, 'git');
});

test('npm lockfile v1', () => {
  const m = parseLockfile(JSON.stringify({ lockfileVersion: 1, dependencies: {
    a: { version: '1.0.0', integrity: 'sha512-a', dependencies: { b: { version: '0.1.0' } } },
    g: { version: 'github:u/g#deadbeef', from: 'github:u/g' },
  } }), 'npm');
  assert.ok(m.has('a@1.0.0') && m.has('b@0.1.0'));
  assert.equal(m.get('g@github:u/g#deadbeef').source, 'git');
});

test('pnpm v9 and v6', () => {
  const v9 = `lockfileVersion: '9.0'

importers:
  .:
    dependencies:
      a:
        specifier: ^1.0.0
        version: 1.0.0

packages:

  a@1.0.0:
    resolution: {integrity: sha512-aaa}
    requiresBuild: true

  '@s/b@2.0.0':
    resolution: {integrity: sha512-bbb}

  c@https://example.com/c.tgz:
    resolution: {tarball: https://example.com/c.tgz}
    version: 1.2.3

snapshots:
  a@1.0.0: {}
`;
  const m = parseAny(v9, 'pnpm-lock.yaml');
  assert.equal(m.get('a@1.0.0').integrity, 'sha512-aaa');
  assert.equal(m.get('a@1.0.0').hasInstallScript, true);
  assert.ok(m.has('@s/b@2.0.0'));
  assert.equal(m.get('c@1.2.3').source, 'url');

  const v6 = `lockfileVersion: '6.0'
packages:
  /a@1.0.0:
    resolution: {integrity: sha512-aaa}
    dev: true
  /@s/b@2.0.0(react@18.0.0):
    resolution: {integrity: sha512-bbb}
    dev: false
`;
  const m6 = parseAny(v6, 'pnpm-lock.yaml');
  assert.equal(m6.get('a@1.0.0').dev, true);
  assert.ok(m6.has('@s/b@2.0.0'));

  const v5 = `lockfileVersion: 5.4
packages:
  /a/1.0.0:
    resolution: {integrity: sha512-aaa}
  /@s/b/2.0.0_react@18.0.0:
    resolution: {integrity: sha512-bbb}
`;
  const m5 = parseAny(v5, 'pnpm-lock.yaml');
  assert.deepEqual([...m5.keys()].sort(), ['@s/b@2.0.0', 'a@1.0.0']);
});

test('yarn v1', () => {
  const y = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@s/b@^2.0.0", "@s/b@^2.1.0":
  version "2.1.0"
  resolved "https://registry.yarnpkg.com/@s/b/-/b-2.1.0.tgz#abc"
  integrity sha512-bbb

a@^1.0.0:
  version "1.0.0"
  resolved "https://registry.yarnpkg.com/a/-/a-1.0.0.tgz"
  integrity sha512-aaa
  dependencies:
    "@s/b" "^2.0.0"

g@git+https://github.com/u/g.git:
  version "0.0.1"
  resolved "git+https://github.com/u/g.git#0123"
`;
  const m = parseAny(y, 'yarn.lock');
  assert.equal(m.get('@s/b@2.1.0').integrity, 'sha512-bbb');
  assert.equal(m.get('a@1.0.0').source, 'registry');
  assert.equal(m.get('g@0.0.1').source, 'git');
});

test('yarn berry', () => {
  const y = `__metadata:
  version: 8
  cacheKey: 10

"a@npm:^1.0.0":
  version: 1.0.0
  resolution: "a@npm:1.0.0"
  checksum: 10/abcdef
  languageName: node
  linkType: hard

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  languageName: unknown
  linkType: soft

"g@https://github.com/u/g.git#commit=abc":
  version: 0.1.0
  resolution: "g@https://github.com/u/g.git#commit=abc"
  languageName: node
  linkType: hard
`;
  const m = parseAny(y, 'yarn.lock');
  assert.deepEqual([...m.keys()].sort(), ['a@1.0.0', 'g@0.1.0']);
  assert.equal(m.get('a@1.0.0').integrity, 'yarn-checksum:10/abcdef');
  assert.equal(m.get('g@0.1.0').source, 'git');
});

test('classifySource', () => {
  assert.equal(classifySource('https://registry.npmjs.org/a/-/a-1.tgz'), 'registry');
  assert.equal(classifySource('https://my.corp/npm/a/-/a-1.tgz'), 'registry');
  assert.equal(classifySource('https://evil.example/a.tgz'), 'url');
  assert.equal(classifySource('git+ssh://git@github.com/a/b.git'), 'git');
  assert.equal(classifySource('file:../x'), 'file');
  assert.equal(classifySource(null), 'registry');
});

test('baseline round trip', () => {
  const m = parseLockfile(JSON.stringify({ lockfileVersion: 3, packages: { 'node_modules/a': { version: '1.0.0', integrity: 'sha512-a' } } }), 'npm');
  const b = JSON.stringify(toBaseline(m));
  const back = parseAny(b);
  assert.equal(back.get('a@1.0.0').integrity, 'sha512-a');
});
